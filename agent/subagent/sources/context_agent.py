"""Context Agent — 뉴스(2차 출처)/정치적 맥락 검색 에이전트.

담당: 다른 팀원(speech/action/context agent 담당) — 단, search_news 연결은
오케스트레이션 쪽에서 NAVER API HUB 뉴스 검색으로 먼저 구현·연결함
(agent/tools/web_search_tool.py 참고).

이 에이전트는 source_verification.py의 context_verified_loop(LoopAgent)에
감싸여 실행된다. context_verifier가 근거 불분명으로 판단하면 session state의
context_retry_hint에 재검색 지시를 남기므로, instruction에서 이 값을 참고해야 한다.
context_verifier는 check_own_actions_only=True로 만들어져 있어, 아래 "본인
발언·행동만 채택" 규칙을 이 파일과 이중으로 검사한다.

버그 기록 (실제로 재현하고 고친 것들):
- tools=[search_news]를 연결해도 "검색하겠습니다"라는 서술만 하고 실제로는
  호출하지 않은 채 답을 지어낸 사례가 있었다. tool_config(ANY 모드)로 매 턴
  강제하는 방법을 시도했으나, 이건 "tool 결과를 받은 뒤 텍스트로 마무리할
  기회"까지 차단해 같은 질문에 12회 넘게 연속 검색만 반복하는 문제를 만들어
  폐기했다. instruction으로만 강하게 명시하는 방식으로 되돌림.
- "본인 발언·행동만 채택하라"는 규칙은 instruction만으로 매번 100% 지켜지지
  않는다(비결정성) — 같은 질문을 반복 실행해도 어떤 때는 본인 발언만 정확히
  걸러내고, 어떤 때는 여론조사·야당 비판을 그대로 답변에 포함시킨다. LLM
  instruction 기반 가드레일의 확률적 한계로 기록해두고, context_verifier의
  이중 검사(체크포인트 3)로 보완한다. 완전한 해결은 tools 실측 데이터에
  근거한 후처리 필터가 필요할 수 있다.
- (실측, 속도-정확도 트레이드오프 3가지 비교) "정청래 법제사법위원회" 같은
  질문에서 근거 부족("정보 없음")이 자주 나오는 문제를 두 가지 방식으로
  고쳐봤다: (a) search_news를 검색어 바꿔가며 순차 최대 3회 재시도 — 근거
  발견률 5/5로 개선됐지만 LoopAgent 재시도까지 겹쳐 응답이 63~98초로
  느려짐. (b) search_news_multi로 여러 검색어를 한 번에 병렬 조회 — 도구
  호출 자체는 0.75초로 빨랐지만 전체 응답은 64~80초로 별 차이 없었고
  정확도도 4/5로 오히려 하락(원인: LoopAgent가 여전히 도는 데다, 후보가
  많아지면서 LLM의 본인 발언 판별이 더 흔들림). 실측 결과 병목은 도구
  호출 시간이 아니라 "LoopAgent가 몇 번 도는가(=LLM을 몇 번 호출하는가)"
  였다 — 검색을 1회로 유지한 원본이 28~65초로 가장 빨랐다. 그래서 (c)
  재검색 자체를 없애고, 그 한 번의 호출에서 display를 10->30으로 늘려
  후보 풀을 넓히는 방식으로 정착했다(web_search_tool.py) — LoopAgent
  재시도 없이 상위 30건 안에서 본인 발언 기사를 찾게 하는 것.
- (추가 실측, 2026-08-25) 전체 파이프라인 프로파일링에서 context_agent
  1회 호출 자체가 18~21초로 fetch(병렬 3갈래) 전체의 최대 병목으로 확인됐다.
  네이버 API 응답은 빠르므로(위 항목 참고) 이 시간은 LLM이 30건을 전부 읽고
  "본인 발언 vs 제3자 재인용"을 판별하는 추론 분량이다. display를 30->25로
  줄여 판별 대상을 20% 낮췄다(web_search_tool.py, 아래 instruction 동기화).
  "정청래 법제사법위원회" 같은 사례에서 근거 발견률이 떨어지는지는 아직
  회귀 확인 전 — 눈에 띄게 나빠지면 30으로 되돌릴 것.
"""
import os

from google.adk.agents import Agent

from agent.tools.web_search_tool import search_news

context_agent = Agent(
    name="context_agent",
    model=os.getenv("MODEL", "gemini-3.5-flash"),
    tools=[search_news],
    instruction="""
    목적: search_news 도구로 뉴스 기사를 검색해, 대상 인물 "본인"의 입장이
    시간에 따라 어떻게 달라졌는지 방향성을 보여준다. 아래 모든 규칙은 이
    목적을 위한 것이다.

    ## 1. 도구 호출
    - search_news를 반드시 실제로 호출한 뒤에만 답하라. "검색하겠습니다"
      같은 예고 서술만 하고 호출을 생략하는 것은 금지 — 그 문장을 쓸 바에야
      바로 도구를 호출하라.
    - 호출은 딱 한 번만(2회 이상은 그만큼 느려짐 — 정확도보다 속도 우선).
      대신 한 번에 최대 25건을 받아 전체를 끝까지 훑어라. 상위 5~10건만
      보고 아래 채택 기준을 통과하는 기사가 없다고 바로 포기하지 마라 —
      실제로 상위권은 제3자가 대상 인물을 언급/비교하는 기사이고, 본인이
      직접 한 말이 인용된 기사는 더 아래 순위에 섞여 있는 경우가 많다.
    - 검색어는 의원 이름 + 구체적인 정책/제도명을 조합해라(예: "홍길동
      종합부동산세"). "국회 부동산" 같은 범용 키워드만 쓰면 지금 이 순간
      가장 화제인 최신 기사에 쏠려서 시간대가 넓어지지 않는다.

    ## 2. 채택 기준 — 아래 세 조건을 모두 만족해야 answer/sources에 쓸 수 있다
    a. 관련성: 검색 대상과 실제로 관련 있다(이름만 우연히 겹친 무관한 기사가
       아님 — 예: "홍길동"이 선거법 판례의 가상 사례나 전단지 시안 예시명으로만
       등장한 경우는 제외).
    b. 본인 발언·행동: 대상 인물 본인이 직접 한 말·행동을 보도한 기사다
       (예: "OO 의원이 ~라고 말했다", "~법안을 발의했다"). 아래 두 유형은
       모두 제외 대상이다 — "본인 발언 인용" 여부만으로는 못 걸러내므로
       각각을 별도로 확인하라:
         - 순수 제3자 평가: 본인의 발언 인용 없이 제3자(여론조사, 야당,
           시민단체, 평론가)의 평가·비판·전망만 있는 기사. "~라는 평가가
           나왔다"처럼 완화해서 넣지 말고 아예 언급하지 마라.
         - 제3자의 간접 재인용: 대상 인물의 발언이 따옴표로 등장해도, 그
           문장 전체의 주어(누가 그렇게 "말했다/발언했다/비판했다"고
           보도하는지)가 대상 인물이 아니라 제3자인 경우(예: "OOO 평론가는
           이 대통령의 '정부 이기는 시장이 없다'는 발언을 두고 '권력의
           오만'이라 비판했다" — 따옴표 속 문구는 대상 인물이 한 말이지만,
           이 문장은 OOO 평론가가 그 발언을 인용하며 비판한 기사이지 대상
           인물이 그 시점에 새로 발언·행동한 기사가 아니다). 이런 재인용을
           "~라는 취지의 발언을 남겼다"처럼 대상 인물이 직접 한 것으로 다시
           쓰지 마라 — 이 기사 자체는 제외하거나, 쓰더라도 "OOO은 대상
           인물의 과거 발언('~')을 인용하며 비판했다"처럼 실제 화자(비판한
           쪽)를 주어로 정확히 밝혀 써라.
         - 예외(포함 가능): 그 기사 안에 본인의 "반응" 발언이 직접
           인용되어 있다면(예: "이에 대해 OO 의원은 '~'라고 답했다") 그
           인용 부분만 골라 써도 된다 — 이건 본인이 그 시점에 실제로 반응한
           것이므로 재인용이 아니다.
    c. 사실 신뢰: 기사에 담긴 사실을 있는 그대로 신뢰한다. 날짜·인물·직책이
       네 학습 시점 지식과 달라 보여도 그건 네가 모르는 최신 사실일 뿐이다.
       "가상 시나리오로 보인다"류 코멘트를 절대 붙이지 마라 — 사실성을
       판단·의심하는 건 네 역할이 아니다.

    ## 3. 기준 미달 시
    위 기준(a·b)을 만족하는 기사가 하나도 없으면 지어내지 말고 다음과 같이
    답하라: 관련 기사 자체가 없으면 "관련 뉴스를 찾지 못했다", 관련 기사는
    있지만 전부 (b) 기준을 통과 못 하면 "본인이 직접 한 발언이나 행동을
    다룬 뉴스를 찾지 못했다" — 두 경우 모두 sources는 빈 배열로 둔다.

    ## 4. 인용 규칙
    기준을 통과한 기사는 제목·요약·날짜·원문 링크를 포함해 정리하라.
    search_news가 준 title과 description은 서로 다른 필드다 — title은 기사
    제목(따옴표가 있어도 대개 편집자가 붙인 헤드라인이지 발언 원문 그대로가
    아니다), description은 본문 요약이다. 요약/인용을 쓸 때는 description
    필드의 내용만 근거로 삼아라. title의 따옴표 문구를 본문에 실제로 있던
    직접 발언인 것처럼 재구성해서 쓰지 마라 — description에 같은 취지의
    서술이 있으면 그 서술 그대로 쓰고, 없으면 "~라고 보도했다"처럼 title을
    있는 그대로 제목으로만 언급해라.

    이전 시도에서 근거가 불분명하다고 판단된 경우, 아래 재검색 지시를 참고해
    다른 키워드·조건으로 다시 검색하라. (첫 시도라 값이 없으면 무시한다.)
    {context_retry_hint?}
    """,
    output_key="context_info",
)
