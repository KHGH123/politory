"""Context Agent — 뉴스(2차 출처)/정치적 맥락 검색 에이전트.

담당: 다른 팀원(speech/action/context agent 담당) — 단, search_news 연결은
오케스트레이션 쪽에서 NAVER API HUB 뉴스 검색으로 먼저 구현·연결함
(agent/tools/web_search_tool.py 참고).

이 에이전트는 source_verification.py의 context_verified_loop(LoopAgent)에
감싸여 실행된다. context_verifier가 근거 불분명으로 판단하면 session state의
context_retry_hint에 재검색 지시를 남기므로, instruction에서 이 값을 참고해야 한다.
context_verifier는 check_own_actions_only=True로 만들어져 있어, 아래 "본인
발언·행동만 채택" 규칙을 이 파일과 이중으로 검사한다.

버그 기록 (실제로 재현하고 고친 것들):
- tools=[search_news]를 연결해도 "검색하겠습니다"라는 서술만 하고 실제로는
  호출하지 않은 채 답을 지어낸 사례가 있었다. tool_config(ANY 모드)로 매 턴
  강제하는 방법을 시도했으나, 이건 "tool 결과를 받은 뒤 텍스트로 마무리할
  기회"까지 차단해 같은 질문에 12회 넘게 연속 검색만 반복하는 문제를 만들어
  폐기했다. instruction으로만 강하게 명시하는 방식으로 되돌림.
- "본인 발언·행동만 채택하라"는 규칙은 instruction만으로 매번 100% 지켜지지
  않는다(비결정성) — 같은 질문을 반복 실행해도 어떤 때는 본인 발언만 정확히
  걸러내고, 어떤 때는 여론조사·야당 비판을 그대로 답변에 포함시킨다. LLM
  instruction 기반 가드레일의 확률적 한계로 기록해두고, context_verifier의
  이중 검사(체크포인트 3)로 보완한다. 완전한 해결은 tools 실측 데이터에
  근거한 후처리 필터가 필요할 수 있다.
"""
import os

from google.adk.agents import Agent

from agent.tools.web_search_tool import search_news

context_agent = Agent(
    name="context_agent",
    model=os.getenv("MODEL", "gemini-3.5-flash"),
    tools=[search_news],
    instruction="""
    search_news 도구로 관련 뉴스 기사와 정치적 맥락(정권 교체, 여야 지위 등)을 검색한다.
    이 서비스의 목적은 대상 인물 본인의 입장이 시간에 따라 어떻게 달라졌는지
    방향성을 보여주는 것이다 — 아래 규칙은 전부 이 목적을 위한 것이다.

    1) 반드시 search_news를 실제로 호출해서 결과를 받은 뒤에만 답하라.
    "검색하겠습니다", "다음 키워드로 검색을 진행합니다" 같은 서술만 하고 실제
    호출을 생략하는 것은 금지된다 — 그 문장을 쓸 바에는 바로 도구를 호출하라.
    search_news는 딱 한 번만 호출해라(2회 이상은 그만큼 응답이 느려짐 —
    정확도보다 속도 우선).

    2) 검색어는 의원 이름 + 구체적인 정책/제도명을 조합해라(예: "홍길동
    종합부동산세", "홍길동 임대차3법"). "국회 부동산" 같은 범용 키워드만 쓰면
    지금 이 순간 가장 화제인 최신 기사에 결과가 쏠려서 시간대가 넓어지지
    않는다.

    3) 채택 기준 — 검색 결과 기사는 세 조건을 모두 만족해야 answer/sources에
    쓸 수 있다:
       a. 검색 대상과 실제로 관련 있다(이름만 우연히 겹친 무관한 기사가 아님 —
          예: "홍길동"이 선거법 판례의 가상 사례나 전단지 시안 예시명으로만
          등장한 경우는 제외).
       b. 대상 인물 본인이 직접 한 말·행동을 보도한 기사다(예: "OO 의원이
          ~라고 말했다", "~법안을 발의했다"). 본인의 발언 인용 없이 제3자
          (여론조사, 야당, 시민단체, 평론가)의 평가·비판·전망만 있는 기사는
          제외한다 — 이런 기사는 "~라는 평가가 나왔다"처럼 완화해서 넣지
          말고 아예 언급하지 마라. 단, 그 기사 안에 본인의 반응 발언이
          직접 인용되어 있다면(예: "이에 대해 OO 의원은 '~'라고 답했다") 그
          인용 부분만 골라 써도 된다.
       c. 기사에 담긴 사실을 있는 그대로 신뢰한다. 날짜·인물·직책이 네
          학습 시점 지식과 달라 보여도 그건 네가 모르는 최신 사실일 뿐이다.
          "가상 시나리오로 보인다"류 코멘트를 절대 붙이지 마라 — 사실성을
          판단·의심하는 건 네 역할이 아니다.

    4) 위 기준(a·b)을 만족하는 기사가 하나도 없으면 지어내지 말고 다음과
    같이 답하라: 관련 기사 자체가 없으면 "관련 뉴스를 찾지 못했다", 관련
    기사는 있지만 전부 (b) 기준을 통과 못 하면 "본인이 직접 한 발언이나
    행동을 다룬 뉴스를 찾지 못했다" — 두 경우 모두 sources는 빈 배열로 둔다.

    5) 기준을 통과한 기사는 제목·요약·날짜·원문 링크를 포함해 정리하라.
    search_news가 준 title과 description은 서로 다른 필드다 — title은 기사
    제목(따옴표가 있어도 그건 대개 편집자가 붙인 헤드라인이지 발언 원문
    그대로가 아니다), description은 본문 요약이다. 요약/인용을 쓸 때는
    description 필드의 내용만 근거로 삼아라. title의 따옴표 문구를 본문에
    실제로 있던 직접 발언인 것처럼 재구성해서 쓰지 마라 — description에
    같은 취지의 서술이 있으면 그 서술 그대로 쓰고, description에 없으면
    "~라고 보도했다"처럼 title을 있는 그대로 제목으로만 언급해라.

    이전 시도에서 근거가 불분명하다고 판단된 경우, 아래 재검색 지시를 참고해
    다른 키워드·조건으로 다시 검색하라. (첫 시도라 값이 없으면 무시한다.)
    {context_retry_hint?}
    """,
    output_key="context_info",
)
